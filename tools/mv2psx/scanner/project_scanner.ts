/**
 * MV2PSX Project Scanner & Feature Detector
 * Adheres to Section 4.1 & 4.3 of the specification.
 * Analyzes project database, maps, and events to extract required runtime features.
 */

import { SystemData, MVMapData, FeatureSet } from '../ir/types.ts';

export class ProjectScanner {
  public scan(system: SystemData, maps: MVMapData[]): FeatureSet {
    const features: FeatureSet = {
      useText: false,
      useChoices: false,
      useSwitches: false,
      useVariables: false,
      useTransfer: false,
      usePictures: false,
      useBattle: false,
      useShop: false,
      useAudioSe: false,
      useAudioBgm: false,
      maxSwitchId: system.switches?.length ? system.switches.length - 1 : 0,
      maxVariableId: system.variables?.length ? system.variables.length - 1 : 0,
    };

    if (system.switches && system.switches.length > 1) {
      features.useSwitches = true;
    }
    if (system.variables && system.variables.length > 1) {
      features.useVariables = true;
    }

    for (const map of maps) {
      if (!map) continue;
      if (map.autoplayBgm) {
        features.useAudioBgm = true;
      }
      if (!map.events) continue;

      for (const ev of map.events) {
        if (!ev) continue;
        for (const page of ev.pages) {
          if (page.conditions?.switch1Valid) {
            features.useSwitches = true;
            if (page.conditions.switch1Id && page.conditions.switch1Id > features.maxSwitchId) {
              features.maxSwitchId = page.conditions.switch1Id;
            }
          }
          if (page.conditions?.variableValid) {
            features.useVariables = true;
            if (page.conditions.variableId && page.conditions.variableId > features.maxVariableId) {
              features.maxVariableId = page.conditions.variableId;
            }
          }

          for (const cmd of page.list || []) {
            switch (cmd.code) {
              case 101:
              case 401:
                features.useText = true;
                break;
              case 102:
                features.useChoices = true;
                break;
              case 121:
                features.useSwitches = true;
                if (cmd.parameters[1] && cmd.parameters[1] > features.maxSwitchId) {
                  features.maxSwitchId = cmd.parameters[1];
                }
                break;
              case 122:
                features.useVariables = true;
                if (cmd.parameters[1] && cmd.parameters[1] > features.maxVariableId) {
                  features.maxVariableId = cmd.parameters[1];
                }
                break;
              case 201:
                features.useTransfer = true;
                break;
              case 231:
                features.usePictures = true;
                break;
              case 301:
                features.useBattle = true;
                break;
              case 302:
                features.useShop = true;
                break;
              case 250:
                features.useAudioSe = true;
                break;
              case 241:
                features.useAudioBgm = true;
                break;
            }
          }
        }
      }
    }

    return features;
  }

  public generateFeaturesHeader(features: FeatureSet): string {
    return `/**
 * Generated by MV2PSX Compiler
 * Automatic Link-time Feature Stripping Configuration
 * Section 4.3 & 5.1 of MV2PSX Technical Specification
 */

#ifndef MVPSX_FEATURES_H
#define MVPSX_FEATURES_H

#define MVPSX_USE_TEXT      ${features.useText ? 1 : 0}
#define MVPSX_USE_CHOICES   ${features.useChoices ? 1 : 0}
#define MVPSX_USE_SWITCHES  ${features.useSwitches ? 1 : 0}
#define MVPSX_USE_VARIABLES ${features.useVariables ? 1 : 0}
#define MVPSX_USE_TRANSFER  ${features.useTransfer ? 1 : 0}
#define MVPSX_USE_PICTURES  ${features.usePictures ? 1 : 0}
#define MVPSX_USE_BATTLE    ${features.useBattle ? 1 : 0}
#define MVPSX_USE_SHOP      ${features.useShop ? 1 : 0}
#define MVPSX_USE_AUDIO_SE  ${features.useAudioSe ? 1 : 0}
#define MVPSX_USE_AUDIO_BGM ${features.useAudioBgm ? 1 : 0}

#define MVPSX_MAX_SWITCHES  ${Math.max(64, features.maxSwitchId + 1)}
#define MVPSX_MAX_VARIABLES ${Math.max(16, features.maxVariableId + 1)}

#endif /* MVPSX_FEATURES_H */
`;
  }
}
